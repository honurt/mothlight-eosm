#!/usr/bin/env python3
"""Turn the M1 Iris logo into a 32x32, 4-level C bitmap for the camera UI.
   0 = transparent, 1 = wing (text colour), 2 = iris (accent), 3 = wing shade (dim)"""
import subprocess, os
from PIL import Image
here = os.path.dirname(os.path.abspath(__file__))
png = "/tmp/m1_64.png"
subprocess.run(["rsvg-convert", "-w", "128", "-h", "128", os.path.join(here, "monogram", "m1-iris.svg"), "-o", png], check=True)
im = Image.open(png).convert("RGB").resize((32, 32), Image.LANCZOS)
ref = {0: (0x14, 0x14, 0x16), 1: (0xF0, 0xED, 0xE6), 2: (0xF5, 0x8C, 0x1E), 3: (0x8C, 0x8A, 0x86)}
def nearest(p):
    return min(ref, key=lambda k: sum((a - b) ** 2 for a, b in zip(p, ref[k])))
px = [nearest(im.getpixel((x, y))) for y in range(32) for x in range(32)]
out = os.path.join(here, "..", "modules", "moth_ui", "logo_icon.h")
with open(out, "w") as f:
    f.write("/* generated by art/make_icon.py from art/monogram/m1-iris.svg -- do not edit */\n")
    f.write("/* 32x32, 0 transparent, 1 wing, 2 iris/accent, 3 wing shade */\n")
    f.write("static const unsigned char logo_icon[32 * 32] = {\n")
    for y in range(32):
        f.write("    " + ",".join(str(v) for v in px[y * 32:(y + 1) * 32]) + ",\n")
    f.write("};\n")
for y in range(32):
    print("".join(" #o+"[v] for v in px[y * 32:(y + 1) * 32]))
