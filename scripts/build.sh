#!/usr/bin/env bash
# Build a card-ready zip for the Canon EOS M (firmware 2.0.2).
#
#   scripts/build.sh                 Crop Mood engine (default: 2.5K/2.8K/3K RAW, 1x3 anamorphic)
#   scripts/build.sh upstream        magiclantern_simplified dev (newest core, basic crop modes only)
#   scripts/build.sh cropmood module only rebuild moth_ui.mo against an already-built engine
#
# Result: out/<engine>/<name>-<version>-<engine>-<date>.zip  (unzip to the root of the SD card)
set -euo pipefail
source "$(dirname "$0")/lib.sh"

ENGINE="${1:-cropmood}"
WHAT="${2:-all}"
DIR="$(engine_dir "$ENGINE")"
VERSION="$(tr -d ' \r\n' < "$ROOT/VERSION")"
NAME="$(tr -d '\r\n' < "$ROOT/NAME" 2> /dev/null || echo mothlight)"
BOOT_LIMIT=727072   # bytes of ML the EOS M boots with (measured on a camera by the M-Film project)

[ -d "$DIR" ] || "$ROOT/scripts/fetch.sh" "$ENGINE"

# ---- our module goes into the engine tree (a copy: edit it in modules/moth_ui, never in work/)
rm -rf "$DIR/modules/moth_ui"
cp -r "$ROOT/modules/moth_ui" "$DIR/modules/moth_ui"
printf '#define MOTH_UI_VERSION "%s"\n#define MOTH_UI_NAME "%s"\n#define MOTH_UI_ENGINE "%s"\n' \
    "$VERSION" "$NAME" "$ENGINE" > "$DIR/modules/moth_ui/version.h"
if [ "$ENGINE" = upstream ]; then
    echo '#define MOTH_ENGINE_UPSTREAM 1' >> "$DIR/modules/moth_ui/version.h"
fi

case "$ENGINE" in
cropmood)
    # The 2023-era build system, made to run with today's tools (see patches/cropmood/0001).
    gcc -O2 -o "$DIR/build_tools/xor_chk" "$DIR/build_tools/xor_chk.c"
    {
        echo "# generated by mothlight scripts/build.sh"
        echo "PYTHON = python3"
        echo "CFLAG_USER = -fcommon"
        echo "ML_MODULES = mlv_lite mlv_play mlv_rec mlv_snd file_man pic_view ettr dual_iso silent \\"
        echo "    autoexpo arkanoid deflick img_name lua bench selftest adv_int crop_rec edmac sd_uhs hdmi_out moth_ui"
    } > "$DIR/Makefile.user"
    MAKE_ARGS=(SHELL=/bin/bash)
    PLAT_DIR="$DIR/platform/$PLATFORM"
    if [ "$WHAT" = module ]; then
        make -C "$DIR/modules/moth_ui" "${MAKE_ARGS[@]}" MODEL=EOSM
        mkdir -p "$OUT/$ENGINE"; cp "$DIR/modules/moth_ui/moth_ui.mo" "$OUT/$ENGINE/"
        say "module: $OUT/$ENGINE/moth_ui.mo"; exit 0
    fi
    say "building Crop Mood engine for $PLATFORM"
    make -C "$PLAT_DIR" "${MAKE_ARGS[@]}" clean > /dev/null 2>&1 || true
    gcc -O2 -o "$DIR/build_tools/xor_chk" "$DIR/build_tools/xor_chk.c"   # clean removes it
    make -C "$PLAT_DIR" "${MAKE_ARGS[@]}" zip > "$WORK/build-$ENGINE.log" 2>&1 \
        || { tail -30 "$WORK/build-$ENGINE.log"; die "build failed (full log: $WORK/build-$ENGINE.log)"; }
    ZIP="$(ls -t "$PLAT_DIR"/magiclantern-*.zip | head -1)"
    ELF="$PLAT_DIR/magiclantern"
    ;;
upstream)
    grep -qx moth_ui "$DIR/platform/$PLATFORM/modules.included" \
        || echo moth_ui >> "$DIR/platform/$PLATFORM/modules.included"
    grep -q "^    moth_ui" "$DIR/modules/Makefile" \
        || sed -i 's/^    yolo$/    yolo \\\n    moth_ui/' "$DIR/modules/Makefile"
    PLAT_DIR="$DIR/platform/$PLATFORM"
    if [ "$WHAT" = module ]; then
        make -C "$DIR/modules/moth_ui" MODEL=EOSM
        mkdir -p "$OUT/$ENGINE"; cp "$DIR/modules/moth_ui/build/moth_ui.mo" "$OUT/$ENGINE/"
        say "module: $OUT/$ENGINE/moth_ui.mo"; exit 0
    fi
    say "building upstream engine for $PLATFORM"
    rm -f "$DIR/modules/build/default_modules_complete"   # module list changed: re-collect the .mo files
    make -C "$PLAT_DIR" clean > /dev/null 2>&1 || true
    make -C "$PLAT_DIR" -j"$(jobs)" > "$WORK/build-$ENGINE.log" 2>&1 \
        || { tail -30 "$WORK/build-$ENGINE.log"; die "build failed (full log: $WORK/build-$ENGINE.log)"; }
    ZIP="$PLAT_DIR/build/magiclantern.zip"
    ELF="$PLAT_DIR/build/magiclantern"
    ;;
*) die "unknown engine '$ENGINE' (cropmood | upstream)" ;;
esac

# ---- boot-size check: too much ML at power-on and the EOS M hangs with the card LED lit
BSS_END=$(arm-none-eabi-nm "$ELF" | awk '$3 == "_bss_end" { print $1 }')
TEXT_START=$(arm-none-eabi-nm "$ELF" | awk '$3 == "_text_start" { print $1 }')
if [ -n "$BSS_END" ] && [ -n "$TEXT_START" ]; then
    BOOT=$(( 16#$BSS_END - 16#$TEXT_START ))
    say "ML at boot: $BOOT bytes (EOS M limit ~$BOOT_LIMIT, $(( BOOT_LIMIT - BOOT )) to spare)"
    [ "$BOOT" -lt "$BOOT_LIMIT" ] || die "autoexec too big for the EOS M -- move features into modules"
else
    warn "could not read boot size from $ELF"
fi

# ---- repack: engine zip + our module + our card files
STAGE="$(mktemp -d)"
unzip -q "$ZIP" -d "$STAGE"
[ -f "$STAGE/ML/modules/moth_ui.mo" ] || die "moth_ui.mo missing from the engine zip (module build failed? see log)"
cp -r "$ROOT/card/." "$STAGE/"
cp "$ROOT/LICENSE" "$STAGE/ML/MOTHLIGHT-LICENSE.txt"
mkdir -p "$OUT/$ENGINE"
DEST="$OUT/$ENGINE/$NAME-$VERSION-$ENGINE-$(date +%Y%m%d).zip"
rm -f "$DEST"
(cd "$STAGE" && zip -qr9 "$DEST" .)
rm -rf "$STAGE"
say "done: $DEST"
